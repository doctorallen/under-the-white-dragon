PX = 100  # one pixel, in font units
def build(out):
    order = ['.notdef'] + sorted(G.keys(), key=lambda c: ord(c))
    names = {c: ('uni%04X' % ord(c)) for c in G}
    glyphs, metrics, cmap = {}, {}, {}
    pen = TTGlyphPen(None); glyphs['.notdef'] = pen.glyph(); metrics['.notdef'] = (5 * PX, 0)
    for c, rows in G.items():
        pen = TTGlyphPen(None); w = len(rows[0])
        for r, row in enumerate(rows):
            y1 = (7 - r) * PX; y0 = y1 - PX  # row 0 is the top of a capital; row 6 sits on the baseline
            x = 0
            while x < w:
                if row[x] == '#':
                    x2 = x
                    while x2 < w and row[x2] == '#': x2 += 1
                    pen.moveTo((x * PX, y0)); pen.lineTo((x * PX, y1)); pen.lineTo((x2 * PX, y1)); pen.lineTo((x2 * PX, y0)); pen.closePath()
                    x = x2
                else: x += 1
        n = names[c]; glyphs[n] = pen.glyph(); metrics[n] = ((w + 1) * PX, 0); cmap[ord(c)] = n
    order = ['.notdef'] + [names[c] for c in sorted(G.keys(), key=ord)]
    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(order); fb.setupCharacterMap(cmap); fb.setupGlyf(glyphs); fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=800, descent=-200)
    fb.setupNameTable({'familyName': 'Dragon Pixel', 'styleName': 'Regular', 'uniqueFontIdentifier': 'DragonPixel-Regular', 'fullName': 'Dragon Pixel', 'psName': 'DragonPixel-Regular', 'version': 'Version 1.0'})
    fb.setupOS2(sTypoAscender=800, sTypoDescender=-200, sTypoLineGap=200, usWinAscent=900, usWinDescent=300)
    fb.setupPost(); fb.setupHead(unitsPerEm=1000)
    fb.font.flavor = 'woff'; fb.save(out)
    print('glyphs', len(G), '->', out)

build(sys.argv[1] if len(sys.argv) > 1 else 'dragon.woff')
